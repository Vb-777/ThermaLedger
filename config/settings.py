"""
ThermaLedger settings.

Two things here matter more than the rest:

1. ATOMIC_REQUESTS = True. The RLS tenant variable is set with
   set_config('app.tenant_id', ..., is_local=true), which is transaction-scoped.
   Every request must therefore run inside a transaction, or the variable would
   either leak across requests on a pooled connection or vanish before the query.

2. The database user must NOT be a superuser and must NOT have BYPASSRLS.
   Postgres silently ignores row-level security for such roles, which would make
   every isolation test pass for the wrong reason. `manage.py enable_rls` refuses
   to run if the connected role can bypass RLS. See tenancy/db.py.
"""

